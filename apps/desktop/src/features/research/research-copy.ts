export type ResearchText = (key: keyof typeof zh, vars?: Record<string, string | number>) => string;
export const researchText: ResearchText = (key, vars) =>
	(getUiLanguage() === "en" ? en[key] : zh[key]).replace(/\{(\w+)\}/g, (raw, name: string) =>
		vars && name in vars ? String(vars[name]) : raw,
	);
export function useResearchText(): ResearchText {
	useT();
	return researchText;
}
