import { createRequire } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';
const require = createRequire('D:/owl/owl-re-v1/owl-mono/package.json');
const { transform } = require('esbuild');
const root = 'D:/owl/owl-re-v1/owl-mono';
const source = await readFile(`${root}/packages/coding-agent/src/core/evaluation/service.ts`, 'utf8');
const compiled = await transform(source, { loader: 'ts', format: 'esm', target: 'node24', sourcefile: 'service.ts' });
const output = compiled.code.replace(/(from\s+["'][.][.\/][^"']+)\.ts(["'])/g, '$1.js$2');
if (!output.includes('thinking: thinking ?? ""') || !output.includes('generationPhase')) throw new Error('Compiled service is missing live thinking projection');
if (/from\s+["'][^"']+\.ts["']/.test(output)) throw new Error('Relative TypeScript imports were not rewritten');
await writeFile(`${root}/.validation/model-evaluation/service.candidate.js`, output);
console.log('Prepared the evaluation service module; the running service was not changed.');
